
# დავალება 1
# 1. შექმენით ოთხი ფუნქცია: შეკრებისთვის, გამოკლებისთვის, გამრავლებისა და გაყოფისთვის.
# 2. თითოეულმა ფუნქციამ უნდა მიიღოს ორი რიცხვი პარამეტრების სახით და შედეგი დააბრუნოს return-ით.
# 3. მომხმარებელს გამოუტანეთ მენიუ, საიდანაც შეძლებს სასურველი მათემატიკური მოქმედების არჩევას.
# 4. მომხმარებელს მოსთხოვეთ ორი რიცხვის შეყვანა და არჩეული მოქმედების შედეგი გამოიტანეთ ეკრანზე.
# 5. გაითვალისწინეთ შემთხვევა, როდესაც მომხმარებელი ცდილობს ნულზე გაყოფას.
# 6. გამოიყენეთ while ციკლი, რათა პროგრამა მუშაობდეს მანამ, სანამ მომხმარებელი არ აირჩევს გასვლას.


# დავალება 2
# 1. შექმენით ფუნქცია, რომელიც მომხმარებელს აჩვენებს მის მიმდინარე ბალანსს.
# 2. შექმენით ფუნქცია, რომელიც მიიღებს შესატან თანხას და ბალანსს შესაბამისი რაოდენობით გაზრდის.
# 3. შექმენით ფუნქცია, რომელიც მომხმარებელს საშუალებას მისცემს ანგარიშიდან გამოიტანოს თანხა. თუ თანხა ბალანსზე მეტია, გამოიტანეთ შესაბამისი შეტყობინება.
# 4. შექმენით ფუნქცია, რომელიც მომხმარებელს საშუალებას მისცემს სხვა ანგარიშზე გადარიცხოს თანხა. გადარიცხვა უნდა შესრულდეს მხოლოდ საკმარისი ბალანსის შემთხვევაში.
# 5. შექმენით ფუნქცია, რომელიც შეინახავს ყველა შესრულებულ ტრანზაქციას სიაში (List). თითოეული ტრანზაქციისთვის შეინახეთ მოქმედების ტიპი და თანხა.
# 6. შექმენით ფუნქცია, რომელიც გამოიტანს ტრანზაქციების ისტორიას.
# 7. ყველა მოქმედებისთვის გამოიყენეთ ცალკეული ფუნქცია და საჭიროების შემთხვევაში შედეგი დააბრუნეთ return-ით.
# 8. შექმენით მენიუ, რომლის საშუალებითაც მომხმარებელი შეძლებს სასურველი მოქმედების არჩევას.
# 9. გამოიყენეთ while ციკლი, რათა პროგრამა მუშაობდეს მანამ, სანამ მომხმარებელი არ აირჩევს გასვლას.
# 10. გაითვალისწინეთ არასწორი თანხის შეყვანა, უარყოფითი რიცხვები და არასაკმარისი ბალანსი.
